/*Escreva um programa que receba um número e verifique se ele está no intervalo entre 10 e 20 (inclusive). 
Exiba no console se o número está ou não no intervalo.*/


var numero = 10

if ((numero >= 10) && (numero <= 20)){
    console.log("O número está entre 10 e 20")
}
else {
    console.log("O número não está entre 10 e 20")
}

